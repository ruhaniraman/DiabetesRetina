"""Neovascularisation (NV) suspicion: does the image-feature model (stage2_structure/nv/nvFeatures.m) pick out proliferative DR?

    python validation/nv_eval.py        # needs results/nv_features.csv (buildNvDataset.m) and the deployed model's test predictions
    python validation/nv_eval.py unet   # the same with vessels from the trained vessel U-Net (nv_features_unet.csv -> nv_unet.md/json)

No problem-statement dataset has pixel masks for new vessels, so the proliferative grade (PDR: new vessels or pre-retinal/vitreous
haemorrhage) is the reference. A logistic regression on the NV features is fitted on the TRAIN rows only and evaluated on the held-out
APTOS and IDRiD test photographs, for two questions:
  1. PDR vs every other grade;
  2. PDR vs Moderate + Severe (telling proliferative disease from other referable disease, where the CNN's grade is weakest).
The CNN's own P(Proliferate_DR) is the baseline. "Combined" is the average of the two scores' ranks with equal weight: nothing is fitted
on test, and the CNN's scores on its own training photographs (which it has memorised) are never used.
Writes results/nv.md and nv.json.
"""
import csv
import json
from pathlib import Path

import numpy as np
from scipy.stats import rankdata
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

RES = Path(__file__).resolve().parent / "results"
CLASSES = ["Mild", "Moderate", "No_DR", "Proliferate_DR", "Severe"]
FEATURES = ["vesselDensity", "vesselDensityDisc", "fineDensity", "fineDensityDisc", "fineDensityElsewhere", "branchDensity", "branchDensityDisc",
            "meanSegmentLength", "meanSegmentLengthDisc", "fineHotspot", "fineHotspotRatio", "heArea", "largestHe", "discFound"]
B = 2000


def auc(score, y):
    pos, neg = score[y], score[~y]
    r = rankdata(np.concatenate([pos, neg]))
    return float((r[: len(pos)].sum() - len(pos) * (len(pos) + 1) / 2) / (len(pos) * len(neg)))


def ci(score, y, seed=5):
    rng = np.random.default_rng(seed)
    n = len(y)
    vals = []
    for _ in range(B):
        k = rng.integers(0, n, n)
        if y[k].any() and (~y[k]).any():
            vals.append(auc(score[k], y[k]))
    return np.percentile(vals, [2.5, 97.5]).tolist()


def recall_at_spec(score, y, spec=0.90):
    """Share of PDR photographs flagged at the threshold that leaves `spec` of the others unflagged."""
    thr = np.quantile(score[~y], spec)
    return float(np.mean(score[y] > thr))


def main(vessels="classical"):
    suffix = "_unet" if vessels == "unet" else ""
    rows = list(csv.DictReader(open(RES / f"nv_features{suffix}.csv", encoding="utf-8")))
    cnn = {}
    for name, prefix in (("deployed_test", "aptos_"), ("ft_run2_finetuned_idrid_test", "")):
        for r in csv.DictReader(open(RES / f"{name}.csv", encoding="utf-8")):
            cnn[prefix + r["id"]] = float(r["p_Proliferate_DR"])
    X = np.array([[float(r[f]) for f in FEATURES] for r in rows])
    y = np.array([r["label"] == "Proliferate_DR" for r in rows])
    train = np.array([r["split"] == "train" for r in rows])
    model = make_pipeline(StandardScaler(), LogisticRegression(C=0.5, class_weight="balanced", max_iter=5000))
    model.fit(X[train], y[train])
    nv = model.predict_proba(X)[:, 1]
    coef = dict(zip(FEATURES, model[-1].coef_[0].round(3).tolist()))

    out = {"train": {"n": int(train.sum()), "pdr": int(y[train].sum())}, "coefficients": coef, "results": {}}
    title = " (vessels from the trained vessel U-Net)" if suffix else ""
    md = [f"# New vessels (neovascularisation): suspicion model{title}", "",
          f"Generated by `validation/nv_eval.py{' unet' if suffix else ''}`. No problem-statement dataset has pixel masks for new vessels, so the model is judged against the "
          "**proliferative grade** (PDR = new vessels or pre-retinal/vitreous haemorrhage). NV features (`stage2_structure/nv/nvFeatures.m`): fine, "
          "densely branching vessels on/near the optic disc and elsewhere, and large haemorrhages. Logistic regression fitted on "
          f"{int(train.sum())} training photographs ({int(y[train].sum())} PDR); evaluated once on the held-out test photographs.", "",
          "| Test set | Question | n (PDR) | CNN P(PDR) AUC | NV model AUC | Combined AUC | PDR found at 90% specificity: CNN / NV / combined |",
          "|---|---|---|---|---|---|---|"]
    for data in ("aptos", "idrid"):
        te = np.array([r["split"] == "test" and r["dataset"] == data for r in rows])
        ids = [r["id"] for r, t in zip(rows, te) if t]
        c = np.array([cnn[i] for i in ids])
        labels = np.array([r["label"] for r, t in zip(rows, te) if t])
        for q, keep in (("PDR vs all other grades", np.ones(len(ids), bool)),
                        ("PDR vs Moderate + Severe", np.isin(labels, ["Proliferate_DR", "Moderate", "Severe"]))):
            yy = labels[keep] == "Proliferate_DR"
            cs, ns = c[keep], nv[te][keep]
            comb = (rankdata(cs) + rankdata(ns)) / 2
            res = {"n": int(keep.sum()), "pdr": int(yy.sum())}
            for name, s in (("cnn", cs), ("nv", ns), ("combined", comb)):
                res[name] = {"auc": auc(s, yy), "auc_ci": ci(s, yy), "recall_at_90spec": recall_at_spec(s, yy)}
            out["results"][f"{data}: {q}"] = res
            f = lambda k: f"{res[k]['auc']:.3f} ({res[k]['auc_ci'][0]:.2f}-{res[k]['auc_ci'][1]:.2f})"
            md.append(f"| {data.upper() if data == 'idrid' else 'APTOS'} | {q} | {res['n']} ({res['pdr']}) | {f('cnn')} | {f('nv')} | {f('combined')} | "
                      f"{res['cnn']['recall_at_90spec']:.0%} / {res['nv']['recall_at_90spec']:.0%} / {res['combined']['recall_at_90spec']:.0%} |")
    r = out["results"]
    better = [k for k, v in r.items() if v["nv"]["auc"] > v["cnn"]["auc"] or v["combined"]["auc_ci"][0] > v["cnn"]["auc"]]
    md += ["", "**Reading this.** The NV features carry real signal for proliferative disease (AUC well above 0.5 on both test sets), and the strongest "
           "feature is the one the anatomy predicts: short, tangled vessel segments. " +
           ("They beat or add to the CNN in: " + "; ".join(better) + "." if better else
            "But they are weaker than the CNN's own P(Proliferate_DR) everywhere, and averaging the two does not help. The NV suspicion score is "
            "therefore **not shown in the app**; it is kept as a validated research component. Detecting new vessels properly needs pixel-level NV "
            "annotations (none of the problem-statement datasets has them; FGADR does, on request).")]
    md += ["", "Largest standardised coefficients (positive = more suspicious of PDR): " +
           ", ".join(f"{k} {v:+.2f}" for k, v in sorted(coef.items(), key=lambda kv: -abs(kv[1]))[:6]) + ".", "",
           "**What this is and is not.** It is an image-level suspicion of proliferative disease built from vessel and haemorrhage features, checked "
           "against grades. It does not outline new vessels, and a high score is not a finding: new vessels need confirmation by an ophthalmologist."]
    (RES / f"nv{suffix}.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    (RES / f"nv{suffix}.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else "classical")
