"""Does the app's low-bandwidth mode change the referral decision? (needs MATLAB; about 25 minutes)

    python validation/compression_eval.py        # writes results/compression.md and results/compression_<set>_<variant>.csv

Low-bandwidth mode (frontend/src/utils/compressImage.js) shrinks a photo in the browser so its longest side is at most 1800 px and
re-encodes it as JPEG, quality 0.85, before upload over a 2G-grade link. Here the same is done to every held-out test photograph (APTOS test
split, 548; IDRiD test set, 103) and both versions are graded by the deployed Stage 3 pipeline (predictFiles, 'crop_mirror', exactly as the
app prepares a photo). Reported: bytes sent, agreement of the referral decision at the deployed threshold, sensitivity / specificity / AUC for
each version, and the largest change in referral score.
"""
import csv
import sys
import tempfile
from pathlib import Path

import cv2
import matlab.engine
import numpy as np

from analyze import DEPLOYED_THRESHOLD

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "validation" / "results"
APTOS = ROOT / "data" / "aptos2019_full" / "train_images"
IDRID = ROOT / "data" / "idrid_grading" / "B. Disease Grading" / "B. Disease Grading"
MAX_SIDE, QUALITY = 1800, 85          # compressImage.js: MAX_SIDE, JPEG_QUALITY 0.85
GRADES = ["No_DR", "Mild", "Moderate", "Severe", "Proliferate_DR"]


def test_sets():
    splits = list(csv.DictReader(open(RES / "splits.csv", encoding="utf-8")))
    aptos = [(r["id"], APTOS / f"{r['id']}.png", r["label"]) for r in splits if r["split"] == "test"]
    labels = list(csv.reader(open(IDRID / "2. Groundtruths" / "b. IDRiD_Disease Grading_Testing Labels.csv", encoding="utf-8-sig")))[1:]
    idrid = [(r[0], IDRID / "1. Original Images" / "b. Testing Set" / f"{r[0]}.jpg", GRADES[int(r[1])]) for r in labels if r and r[0]]
    return {"aptos": aptos, "idrid": idrid}


def low_bandwidth_copy(src: Path, dst: Path) -> int:
    img = cv2.imread(str(src), cv2.IMREAD_COLOR)
    h, w = img.shape[:2]
    s = min(1.0, MAX_SIDE / max(h, w))
    if s < 1:
        img = cv2.resize(img, (round(w * s), round(h * s)), interpolation=cv2.INTER_AREA)
    cv2.imwrite(str(dst), img, [cv2.IMWRITE_JPEG_QUALITY, QUALITY])
    return dst.stat().st_size


def read_scores(path):
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    return {r["id"]: (r["label"], sum(float(r[f"p_{c}"]) for c in ("Moderate", "Severe", "Proliferate_DR"))) for r in rows}


def rates(labels, scores, thr):
    ref = np.array([GRADES.index(l) >= 2 for l in labels])
    flag = np.array(scores) >= thr
    sens = (flag & ref).sum() / max(ref.sum(), 1)
    spec = (~flag & ~ref).sum() / max((~ref).sum(), 1)
    pos, neg = np.array(scores)[ref], np.array(scores)[~ref]
    auc = (np.sum(pos[:, None] > neg[None, :]) + 0.5 * np.sum(pos[:, None] == neg[None, :])) / (len(pos) * len(neg))
    return sens, spec, auc


def main():
    eng = matlab.engine.start_matlab()
    for rel in ["utils", "stage_3", "stage1_quality", "validation"]:
        eng.addpath(str(ROOT / rel), nargout=0)
    md = ["# Low-bandwidth mode: does compressing the photo change the referral?", "",
          f"Generated by `validation/compression_eval.py`. Each held-out test photograph was graded twice by the deployed Stage 3 pipeline: as the "
          f"original file, and as the app's low-bandwidth upload (longest side at most {MAX_SIDE} px, JPEG quality {QUALITY}, as "
          f"`frontend/src/utils/compressImage.js` makes it). Referral threshold {DEPLOYED_THRESHOLD}. 2G-grade link: 0.1 Mbps with 60% usable and "
          "10% protocol overhead (Stage 5 assumptions).", "",
          "| Test set | Photos | Median size: original → sent | Upload per eye on 2G: original → sent | Same referral decision | "
          "Sensitivity original / sent | Specificity original / sent | AUC original / sent | Largest score change |",
          "|---|---|---|---|---|---|---|---|---|"]
    with tempfile.TemporaryDirectory(prefix="lowbw_") as tmp:
        for name, items in test_sets().items():
            ids = [i for i, _, _ in items]
            labels = [l for _, _, l in items]
            sizes_orig = [p.stat().st_size for _, p, _ in items]
            small = [Path(tmp) / f"{name}_{i}.jpg" for i in ids]
            sizes_sent = [low_bandwidth_copy(p, d) for (_, p, _), d in zip(items, small)]
            out = {}
            for variant, paths in (("original", [str(p) for _, p, _ in items]), ("lowbandwidth", [str(p) for p in small])):
                csv_path = RES / f"compression_{name}_{variant}.csv"
                eng.predictFiles(paths, labels, csv_path.as_posix(), ids, "crop_mirror", nargout=0)
                out[variant] = read_scores(csv_path)
                print("done", name, variant, flush=True)
            a = np.array([out["original"][i][1] for i in ids]); b = np.array([out["lowbandwidth"][i][1] for i in ids])
            same = np.mean((a >= DEPLOYED_THRESHOLD) == (b >= DEPLOYED_THRESHOLD))
            ra, rb = rates(labels, a, DEPLOYED_THRESHOLD), rates(labels, b, DEPLOYED_THRESHOLD)
            secs = lambda n: n * 8 * 1.1 / 60000
            mo, ms = np.median(sizes_orig), np.median(sizes_sent)
            md.append(f"| {name.upper()} test | {len(ids)} | {mo / 1e6:.2f} MB → {ms / 1e6:.2f} MB | {secs(mo):.0f} s → {secs(ms):.0f} s | "
                      f"{100 * same:.1f}% ({int(round((1 - same) * len(ids)))} changed) | {100 * ra[0]:.1f}% / {100 * rb[0]:.1f}% | "
                      f"{100 * ra[1]:.1f}% / {100 * rb[1]:.1f}% | {ra[2]:.3f} / {rb[2]:.3f} | {np.max(np.abs(a - b)):.3f} |")
    eng.quit()
    md += ["", "APTOS originals are the competition's full-resolution PNG files (lossless, so their size overstates a camera's JPEG); IDRiD "
           "originals are the camera's own JPEG files. A decision that changes is a photo whose referral score sits close to the threshold."]
    (RES / "compression.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")        # the report has arrows a Windows console code page cannot print
    print("\n".join(md))


if __name__ == "__main__":
    main()
